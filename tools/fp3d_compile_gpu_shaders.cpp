// Compile the exact HLSL in the native GPU pipeline to reproducible DXBC.
// Invoke from the source root with output path src/fp3d_gpu_base_shaders.inc.
#include <d3dcompiler.h>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <iterator>
#include <memory>
#include <stdexcept>
#include <string>
#include "../src/fp3d_gpu_textured.h"
#include "../src/fp3d_gpu_sky.h"
#include "../src/fp3d_gpu_halo.h"
#include "../src/fp3d_gpu_photon.h"
namespace {
struct release_blob { void operator()(ID3DBlob *p) const { if(p) p->Release(); } };
bool emit(FILE *out,const char *name,const char *source,const char *profile,
          const D3D_SHADER_MACRO *defines = nullptr) {
    ID3DBlob *raw=nullptr,*errors=nullptr;
    const HRESULT hr=D3DCompile(source,std::strlen(source),name,defines,nullptr,
        "main",profile,D3DCOMPILE_ENABLE_STRICTNESS,0,&raw,&errors);
    std::unique_ptr<ID3DBlob,release_blob> bytes(raw),diagnostics(errors);
    if(FAILED(hr)) {
        if(diagnostics) std::fprintf(stderr,"%.*s\n",(int)diagnostics->GetBufferSize(),
                                      (const char*)diagnostics->GetBufferPointer());
        return false;
    }
    std::fprintf(out,"inline constexpr unsigned char %s[] = {\n",name);
    const auto *p=static_cast<const unsigned char *>(bytes->GetBufferPointer());
    for(std::size_t i=0;i<bytes->GetBufferSize();++i) {
        std::fprintf(out,"0x%02x,",unsigned(p[i]));
        if(i%16==15) std::fputc('\n',out);
    }
    std::fputs("\n};\n",out);
    return true;
}
}
int main(int argc,char **argv) {
    if(argc!=2) return 2;
    std::ifstream compute_source( "src/fp3d_gpu_terrain_compute.hlsl", std::ios::binary );
    const std::string compute{ std::istreambuf_iterator<char>( compute_source ), {} };
    std::ifstream occlusion_source( "src/fp3d_gpu_occlusion.hlsl", std::ios::binary );
    const std::string occlusion{ std::istreambuf_iterator<char>( occlusion_source ), {} };
    if( compute.empty() || occlusion.empty() ) {
        std::fputs( "Unable to read compute HLSL from the source root.\n", stderr );
        return 1;
    }
    std::unique_ptr<FILE,decltype(&std::fclose)> output(std::fopen(argv[1],"wb"),std::fclose);
    if(!output) return 1;
    std::fputs("// Generated by tools/fp3d_compile_gpu_shaders.cpp; do not hand edit.\n"
               "namespace fp3d_gpu_shader_bytes {\n",output.get());
    const D3D_SHADER_MACRO shadow_caster[] = {{"FP3D_SHADOW_CASTER","1"},{nullptr,nullptr}};
    const D3D_SHADER_MACRO reflectivity_mask[] = {{"FP3D_REFLECTIVITY_MASK","1"},{nullptr,nullptr}};
    const D3D_SHADER_MACRO occlusion_reduce[] = {{"FP3D_OCCLUSION_REDUCE","1"},{nullptr,nullptr}};
    if(!emit(output.get(),"base_vertex",fp3d_gpu::textured_vertex_hlsl,"vs_5_1") ||
        !emit(output.get(),"base_fragment",fp3d_gpu::textured_fragment_hlsl,"ps_5_1") ||
        !emit(output.get(),"shadow_caster_fragment",fp3d_gpu::textured_fragment_hlsl,"ps_5_1",
              shadow_caster) ||
        !emit(output.get(),"reflectivity_mask_fragment",fp3d_gpu::textured_fragment_hlsl,"ps_5_1",
              reflectivity_mask) ||
        !emit(output.get(),"sky_vertex",fp3d_gpu::sky_vertex_hlsl,"vs_5_1") ||
        !emit(output.get(),"sky_fragment",fp3d_gpu::sky_fragment_hlsl,"ps_5_1") ||
        !emit(output.get(),"halo_vertex",fp3d_gpu::halo_vertex_hlsl,"vs_5_1") ||
        !emit(output.get(),"halo_fragment",fp3d_gpu::halo_fragment_hlsl,"ps_5_1") ||
        !emit(output.get(),"photon_vertex",fp3d_gpu::photon_vertex_hlsl,"vs_5_1") ||
        !emit(output.get(),"photon_fragment",fp3d_gpu::photon_fragment_hlsl,"ps_5_1") ||
        !emit(output.get(),"terrain_compute",compute.c_str(),"cs_5_1") ||
        !emit(output.get(),"occlusion_reduce",occlusion.c_str(),"cs_5_1",occlusion_reduce) ||
        !emit(output.get(),"occlusion_filter",occlusion.c_str(),"cs_5_1")) return 1;
    std::fputs("}\n",output.get());
    return std::ferror(output.get())?1:0;
}
